import AppKit
import UniformTypeIdentifiers

/// Watches the general pasteboard and feeds new copies into the store.
///
/// macOS has no "clipboard changed" notification, so we compare `changeCount` on a cheap timer
/// and only read the contents when it moves.
final class ClipboardMonitor {
    private let pasteboard = NSPasteboard.general
    private weak var store: ClipboardStore?
    private var timer: Timer?
    private var lastChangeCount: Int

    /// Markers that password managers and similar tools put on secrets (see nspasteboard.org).
    private static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "de.petermaurer.TransientPasteboardType",
        "com.typeit4me.clipping",
        "Pasteboard generator type",
    ]

    private static let ignoredApps: Set<String> = [
        "com.apple.Passwords",
        "com.apple.keychainaccess",
    ]

    private static let maxTextLength = 1_000_000

    init(store: ClipboardStore) {
        self.store = store
        // Start from what's on the clipboard now; only copies made from here on are recorded.
        lastChangeCount = pasteboard.changeCount
    }

    func start() {
        let timer = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in self?.tick() }
        timer.tolerance = 0.25
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
        refreshAccessState()
    }

    /// Called right after the app writes to the pasteboard so its own copy isn't recorded again.
    func syncChangeCount() {
        lastChangeCount = pasteboard.changeCount
    }

    func refreshAccessState() {
        if #available(macOS 15.4, *) {
            store?.accessDenied = pasteboard.accessBehavior == .alwaysDeny
        }
    }

    private func tick() {
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        guard let store, !store.isPaused else { return }
        capture(into: store)
    }

    private func capture(into store: ClipboardStore) {
        let types = Set((pasteboard.types ?? []).map(\.rawValue))
        guard !types.isEmpty, types.isDisjoint(with: Self.ignoredTypes) else { return }
        if let app = NSWorkspace.shared.frontmostApplication?.bundleIdentifier,
           Self.ignoredApps.contains(app) {
            return
        }

        // 1. Files copied in Finder: keep photos, GIFs and videos; ignore other files
        //    (and the file-name text Finder adds alongside them).
        if let urls = pasteboard.readObjects(
            forClasses: [NSURL.self],
            options: [.urlReadingFileURLsOnly: true]
        ) as? [URL], !urls.isEmpty {
            let files = urls.compactMap { url in MediaKind(fileURL: url).map { ($0, url) } }
            store.addMediaFiles(files)
            return
        }

        // 2. Raw image data, unless the copy is really text that also carries a picture
        //    (Word, Excel and Keynote put an image of the selection next to the text).
        let string = pasteboard.string(forType: .string)
        let hasRealText = string.map { Self.isMeaningfulText($0) } ?? false
        if !hasRealText, let image = readImage(types) {
            store.addImageData(image.data, kind: image.kind, needsPNGConversion: image.needsConversion)
            return
        }

        // 3. Plain text.
        if let string, !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            store.addText(String(string.prefix(Self.maxTextLength)))
        }
    }

    private func readImage(_ types: Set<String>) -> (data: Data, kind: MediaKind, needsConversion: Bool)? {
        let gif = NSPasteboard.PasteboardType(UTType.gif.identifier)
        if types.contains(gif.rawValue), let data = pasteboard.data(forType: gif) {
            return (data, .gif, false)
        }
        if let data = pasteboard.data(forType: .png) {
            return (data, .photo, false)
        }
        if let data = pasteboard.data(forType: .tiff) {
            return (data, .photo, true)
        }
        return nil
    }

    /// Text that is more than just the source URL a browser adds when you "Copy Image".
    private static func isMeaningfulText(_ string: String) -> Bool {
        let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return false }
        let isSingleURL = !trimmed.contains(where: \.isWhitespace)
            && (URL(string: trimmed)?.scheme?.hasPrefix("http") ?? false)
        return !isSingleURL
    }
}
